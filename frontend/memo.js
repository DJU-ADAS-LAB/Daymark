(() => {
  'use strict';

  const key = 'daymark.memo.v2';
  const plainTextKey = 'daymark.memo.v1';
  const tabsKey = 'daymark.memo.tabs.v1';
  const editor = document.getElementById('memo-text');
  const tools = document.getElementById('memo-tools');
  const status = document.getElementById('memo-status');
  const nativeWindow = window.__TAURI__?.window.getCurrentWindow();
  const invoke = window.__TAURI__?.core.invoke;
  const detachedId = nativeWindow?.label.startsWith('memo-tab-') ? nativeWindow.label.slice(9) : null;
  const tabBar = document.getElementById('memo-tab-bar');
  let saveQueue = Promise.resolve();
  let tabs = [];
  let activeId;
  let deletingId;
  let detached = new Set();
  if (nativeWindow) document.body.classList.add('native-window');
  if (detachedId) tabBar.hidden = true;

  function showStatus(message = '') {
    status.textContent = message;
    status.hidden = !message;
  }

  // Restore only the elements generated by the editor, without HTML attributes.
  function restoreFormattedMemo(html) {
    const template = document.createElement('template');
    template.innerHTML = html;
    const allowed = new Set(['B', 'STRONG', 'I', 'EM', 'U', 'S', 'STRIKE', 'DEL', 'UL', 'OL', 'LI', 'DIV', 'P', 'BR']);
    function appendContent(source, target) {
      for (const node of source.childNodes) {
        if (node.nodeType === Node.TEXT_NODE) {
          target.append(node.textContent);
        } else if (node.nodeType === Node.ELEMENT_NODE && allowed.has(node.tagName)) {
          const clean = document.createElement(node.tagName.toLowerCase());
          appendContent(node, clean);
          target.append(clean);
        } else if (node.nodeType === Node.ELEMENT_NODE && node.tagName === 'SPAN') {
          appendContent(node, target);
        }
      }
    }
    appendContent(template.content, editor);
  }

  function legacyMemo() {
    const formatted = localStorage.getItem(key);
    if (formatted !== null) return formatted;
    const plainText = localStorage.getItem(plainTextKey);
    if (plainText === null) return null;
    const wrapper = document.createElement('div');
    wrapper.textContent = plainText;
    return wrapper.innerHTML;
  }

  async function loadMemo() {
    try {
      let legacy;
      try {
        legacy = legacyMemo();
      } catch (error) {
        if (!nativeWindow) throw error;
        console.error('기존 메모를 읽지 못했습니다.', error);
      }
      const saved = nativeWindow
        ? await invoke('load_document', { document: 'memo_tabs' })
        : localStorage.getItem(tabsKey);
      if (saved !== null) {
        ({ tabs, activeId } = JSON.parse(saved));
        if (!Array.isArray(tabs) || !tabs.some(tab => tab.id === activeId)) throw new Error('잘못된 메모 탭 데이터');
      } else {
        const formatted = nativeWindow
          ? await window.__TAURI__.core.invoke('load_document', { document: 'memo', legacy })
          : legacy;
        activeId = crypto.randomUUID();
        tabs = [{ id: activeId, title: '메모 1', html: formatted ?? '' }];
        if (nativeWindow) {
          await invoke('load_document', { document: 'memo_tabs', legacy: JSON.stringify({ tabs, activeId }) });
        }
      }
      if (detachedId) activeId = detachedId;
      else if (nativeWindow) detached = new Set(await invoke('detached_memo_ids'));
      renderTabs();
      document.getElementById('add-memo-tab').disabled = false;
      editor.focus();
    } catch (error) {
      showStatus('불러오기 실패');
      console.error(error);
    }
  }

  function saveTabs(edit) {
    const data = JSON.stringify({ tabs, activeId });
    saveQueue = saveQueue.then(async () => {
      if (nativeWindow) {
        await invoke('edit_memo_tab', { edit });
      } else {
        localStorage.setItem(tabsKey, data);
      }
      showStatus();
      return true;
    }).catch(error => {
      showStatus('저장 실패');
      console.error(error);
      return false;
    });
  }
  function saveMemo() {
    const tab = tabs.find(item => item.id === activeId);
    if (!tab) return;
    tab.html = editor.innerHTML;
    saveTabs({ type: 'content', id: tab.id, html: tab.html });
  }

  function visibleTabs() {
    return detachedId ? tabs.filter(tab => tab.id === detachedId) : tabs.filter(tab => !detached.has(tab.id));
  }

  function renderTabs(keepEditor = false) {
    const list = document.getElementById('memo-tabs');
    list.replaceChildren();
    const visible = visibleTabs();
    if (!visible.some(tab => tab.id === activeId)) activeId = visible[0]?.id;
    for (const tab of visible) {
      const item = document.createElement('div');
      item.className = 'memo-tab';
      const button = document.createElement('button');
      button.type = 'button';
      button.dataset.memoTab = tab.id;
      button.textContent = tab.title;
      button.title = tab.title;
      button.setAttribute('aria-pressed', String(tab.id === activeId));
      button.addEventListener('click', () => {
        if (tab.id === activeId) return;
        activeId = tab.id;
        renderTabs();
        saveTabs({ type: 'select', id: tab.id });
        editor.focus();
      });
      item.append(button);
      if (!detachedId) {
        const remove = document.createElement('button');
        remove.type = 'button';
        remove.className = 'memo-tab-remove';
        remove.textContent = '×';
        remove.disabled = tabs.length <= 1;
        remove.setAttribute('aria-label', `${tab.title} 삭제`);
        remove.title = remove.disabled ? '마지막 메모는 삭제할 수 없습니다.' : '메모 탭 삭제';
        remove.addEventListener('click', () => {
          deletingId = tab.id;
          document.getElementById('memo-delete-message').textContent = `‘${tab.title}’ 메모를 삭제할까요?`;
          document.getElementById('memo-delete').showModal();
        });
        item.append(remove);
      }
      list.append(item);
    }
    const active = visible.find(tab => tab.id === activeId);
    const title = document.getElementById('detached-memo-title');
    if (detachedId) {
      title.hidden = false;
      title.textContent = active?.title ?? '';
      if (active) document.title = active.title;
    }
    document.getElementById('rename-memo-tab').disabled = !active;
    editor.contentEditable = String(!!active);
    editor.dataset.placeholder = active ? '기억해 둘 내용을 적어보세요.' : '＋ 버튼으로 메모를 추가할 수 있어요.';
    if (!keepEditor) {
      editor.replaceChildren();
      lastSelection = undefined;
      if (active) restoreFormattedMemo(active.html);
    }
  }

  document.getElementById('add-memo-tab').addEventListener('click', () => {
    let number = 1;
    while (tabs.some(tab => tab.title === `메모 ${number}`)) number++;
    activeId = crypto.randomUUID();
    const title = `메모 ${number}`;
    tabs.push({ id: activeId, title, html: '' });
    renderTabs();
    saveTabs({ type: 'add', id: activeId, title });
    editor.focus();
  });
  document.getElementById('rename-memo-tab').addEventListener('click', () => {
    const tab = tabs.find(item => item.id === activeId);
    const dialog = document.getElementById('memo-rename');
    const input = document.getElementById('memo-tab-title');
    input.value = tab.title;
    dialog.showModal();
    input.select();
  });
  document.getElementById('memo-rename-form').addEventListener('submit', event => {
    event.preventDefault();
    const title = document.getElementById('memo-tab-title').value.trim();
    if (!title) return;
    tabs.find(tab => tab.id === activeId).title = title;
    document.getElementById('memo-rename').close();
    renderTabs();
    saveTabs({ type: 'rename', id: activeId, title });
  });
  document.getElementById('memo-delete-confirm').addEventListener('click', () => {
    const index = tabs.findIndex(tab => tab.id === deletingId);
    deletingId = undefined;
    if (index < 0 || tabs.length <= 1) return;
    const [removed] = tabs.splice(index, 1);
    const keepEditor = removed.id !== activeId;
    if (!keepEditor) activeId = visibleTabs()[0]?.id;
    renderTabs(keepEditor);
    saveTabs({ type: 'delete', id: removed.id });
  });

  if (nativeWindow && !detachedId) {
    let drag;
    let detaching = false;
    let ignoreClick = false;
    tabBar.classList.add('detachable-tabs');
    const dropPreview = document.getElementById('memo-drop-preview');
    function showDropPreview(visible) {
      tabBar.classList.toggle('memo-drop-target', visible);
      dropPreview.hidden = !visible;
    }
    nativeWindow.listen('daymark-memo-drop-preview', event => showDropPreview(event.payload)).catch(console.error);
    const updateDropTarget = () => {
      const { left, top, width, height } = tabBar.getBoundingClientRect();
      invoke('register_memo_tab_bar', { bounds: { left, top, width, height } }).catch(console.error);
    };
    new ResizeObserver(updateDropTarget).observe(tabBar);
    updateDropTarget();
    tabBar.addEventListener('pointerdown', event => {
      const button = event.target.closest('[data-memo-tab]');
      if (!button || event.button !== 0 || !event.isPrimary || detaching) return;
      ignoreClick = false;
      drag = { id: button.dataset.memoTab, pointer: event.pointerId, x: event.clientX, y: event.clientY };
    });
    function outsideTabBar(event) {
      const bounds = tabBar.getBoundingClientRect();
      return event.clientY < bounds.top - 14 || event.clientY > bounds.bottom + 14
        || event.clientX < bounds.left - 14 || event.clientX > bounds.right + 14;
    }
    window.addEventListener('pointermove', event => {
      if (!drag || event.pointerId !== drag.pointer) return;
      if (!drag.captured && Math.hypot(event.clientX - drag.x, event.clientY - drag.y) >= 8) {
        tabBar.setPointerCapture(event.pointerId);
        drag.captured = true;
      }
      tabBar.classList.toggle('detaching-tab', drag.captured && outsideTabBar(event));
    });
    async function endDrag(event) {
      if (!drag || drag.pointer !== event.pointerId) return;
      const { id, captured } = drag;
      drag = undefined;
      tabBar.classList.remove('detaching-tab');
      if (event.type !== 'pointerup' || !captured || !outsideTabBar(event)) return;
      ignoreClick = true;
      detaching = true;
      try {
        if (await saveQueue === false) throw new Error('메모를 먼저 저장해야 합니다.');
        await invoke('detach_memo_tab', { id });
        detached.add(id);
        if (id === activeId) renderTabs();
        else tabBar.querySelector(`[data-memo-tab="${CSS.escape(id)}"]`)?.closest('.memo-tab').remove();
      } catch (error) {
        showStatus('메모 탭 분리 실패');
        console.error(error);
      } finally {
        detaching = false;
      }
    }
    window.addEventListener('pointerup', endDrag);
    window.addEventListener('pointercancel', endDrag);
    tabBar.addEventListener('click', event => {
      if (ignoreClick && event.detail !== 0) {
        ignoreClick = false;
        event.stopPropagation();
      }
    }, true);
    nativeWindow.listen('daymark-memo-reattached', async event => {
      showDropPreview(false);
      try {
        await saveQueue;
        const previous = tabs.find(tab => tab.id === activeId);
        const [saved, ids] = await Promise.all([
          invoke('load_document', { document: 'memo_tabs' }),
          invoke('detached_memo_ids')
        ]);
        ({ tabs } = JSON.parse(saved));
        detached = new Set(ids);
        detached.delete(event.payload);
        const active = tabs.find(tab => tab.id === activeId);
        const keepEditor = !!previous && !!active && !detached.has(activeId);
        if (keepEditor) active.html = editor.innerHTML;
        renderTabs(keepEditor);
        const returned = tabBar.querySelector(`[data-memo-tab="${CSS.escape(event.payload)}"]`)?.closest('.memo-tab');
        if (returned) {
          returned.classList.add('memo-tab-returned');
          returned.scrollIntoView({ block: 'nearest', inline: 'nearest' });
        }
      } catch (error) {
        showStatus('메모 탭을 불러오지 못했습니다.');
        console.error(error);
      }
    }).catch(console.error);
  }
  if (detachedId) {
    const handle = document.getElementById('detached-memo-title');
    let drag;
    let moving = Promise.resolve();
    let movePending = false;
    handle.title = '원래 메모 창의 탭바로 드래그하면 다시 들어갑니다.';
    handle.addEventListener('pointerdown', event => {
      if (!event.isPrimary || event.button !== 0 || drag) return;
      handle.setPointerCapture(event.pointerId);
      const offset = invoke('begin_memo_tab_drag').catch(error => {
        console.error(error);
        return null;
      });
      drag = { pointer: event.pointerId, x: event.clientX, y: event.clientY, offset, started: false };
    });
    handle.addEventListener('pointermove', event => {
      if (!drag || drag.pointer !== event.pointerId) return;
      if (!drag.started && Math.hypot(event.clientX - drag.x, event.clientY - drag.y) < 6) return;
      drag.started = true;
      if (movePending) return;
      movePending = true;
      moving = drag.offset.then(offset => {
        if (offset) return invoke('place_memo_tab', { offset });
      }).catch(console.error).finally(() => { movePending = false; });
    });
    async function finish(event) {
      if (!drag || event.pointerId !== drag.pointer) return;
      const current = drag;
      drag = undefined;
      if (!current.started) return;
      if (event.type !== 'pointerup') {
        await moving;
        invoke('clear_memo_drop_preview').catch(console.error);
        return;
      }
      const dropPosition = window.__TAURI__.window.cursorPosition().catch(error => {
        console.error(error);
        return null;
      });
      try {
        await moving;
        const offset = await current.offset;
        const cursor = await dropPosition;
        if (!offset || !cursor) return;
        if (await saveQueue === false) throw new Error('메모를 먼저 저장해야 합니다.');
        await invoke('place_memo_tab', { offset, dropPosition: [cursor.x, cursor.y] });
      } catch (error) {
        showStatus('메모 탭 이동 실패');
        console.error(error);
      } finally {
        invoke('clear_memo_drop_preview').catch(() => {});
      }
    }
    handle.addEventListener('pointerup', finish);
    handle.addEventListener('pointercancel', finish);
  }
  editor.addEventListener('input', saveMemo);
  editor.addEventListener('paste', event => {
    event.preventDefault();
    document.execCommand('insertText', false, event.clipboardData.getData('text/plain'));
  });
  editor.addEventListener('drop', event => event.preventDefault());

  let lastSelection;
  document.addEventListener('selectionchange', () => {
    const selection = window.getSelection();
    if (selection.rangeCount && editor.contains(selection.getRangeAt(0).commonAncestorContainer)) {
      lastSelection = selection.getRangeAt(0).cloneRange();
    }
  });
  tools.addEventListener('mousedown', event => {
    if (event.target.closest('button')) event.preventDefault();
  });
  tools.addEventListener('click', event => {
    const button = event.target.closest('[data-format]');
    if (!button || !editor.isContentEditable) return;
    editor.focus();
    if (lastSelection) {
      const selection = window.getSelection();
      selection.removeAllRanges();
      selection.addRange(lastSelection);
    }
    document.execCommand(button.dataset.format);
    saveMemo();
  });
  loadMemo();

  async function closeMemo() {
    try {
      await saveQueue;
      if (nativeWindow) await nativeWindow.close();
      else window.close();
    } catch (error) {
      showStatus('닫기 실패');
      console.error(error);
    }
  }

  document.getElementById('close-memo').addEventListener('click', closeMemo);
  document.addEventListener('keydown', event => {
    if (event.key === 'Escape' && !event.isComposing && !document.querySelector('dialog[open]')) closeMemo();
  });
})();
